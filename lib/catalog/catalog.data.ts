export function getCatalogItemById(id: string): (CatalogSeedItem & { id: string }) | undefined {
  const all = CATALOG_ITEMS.map((c) => ({
    ...c,
    id: `cat_${c.category}_${c.name.toLowerCase().replace(/[^a-z0-9]/g, '_')}`,
  }));
  return all.find((item) => item.id === id);
}
