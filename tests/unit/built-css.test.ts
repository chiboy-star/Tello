import { describe, it, expect } from 'vitest';
import fs from 'fs';
import path from 'path';

describe('Production Built CSS Regression Test', () => {
  it('verifies built CSS bundle exists and contains compiled Tailwind utility classes', () => {
    const cssDir = path.resolve(process.cwd(), '.next/static/css');
    expect(fs.existsSync(cssDir)).toBe(true);

    const cssFiles = fs.readdirSync(cssDir).filter((file) => file.endsWith('.css'));
    expect(cssFiles.length).toBeGreaterThan(0);

    let totalCssContent = '';
    for (const file of cssFiles) {
      const content = fs.readFileSync(path.join(cssDir, file), 'utf-8');
      totalCssContent += content;
    }

    // Must be compiled Tailwind stylesheet, not just empty layer definitions
    expect(totalCssContent.length).toBeGreaterThan(40000);

    // Essential utility classes that must be generated by Tailwind v4
    expect(totalCssContent).toContain('.flex{');
    expect(totalCssContent).toContain('.grid{');
    expect(totalCssContent).toContain('.inline-flex{');
    expect(totalCssContent).toContain('.hidden{');
    expect(totalCssContent).toContain('--brand');
    expect(totalCssContent).toContain('--accent');
  });
});
